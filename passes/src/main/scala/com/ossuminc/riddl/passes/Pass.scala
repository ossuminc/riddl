  def closeInclude(include: Include[?], parents: Parents): Unit
  def closeBASTImport(bi: BASTImport, parents: Parents): Unit

  // LeafDefinitions
  def doField(field: Field): Unit
  def doMethod(method: Method): Unit
  def doAuthor(author: Author): Unit
  def doConstant(constant: Constant): Unit
  def doInvariant(invariant: Invariant): Unit
  def doVersion(version: Version): Unit
  def doCopyright(copyright: Copyright): Unit
  def doSagaStep(sagaStep: SagaStep): Unit
  def doInlet(inlet: Inlet): Unit
  def doOutlet(outlet: Outlet): Unit
  def doConnector(connector: Connector): Unit
  def doUser(user: User): Unit
  def doSchema(schema: Schema): Unit
  def doRelationship(relationship: Relationship): Unit
  def doEnumerator(enumerator: Enumerator): Unit
  def doContainedGroup(containedGroup: ContainedGroup): Unit

  // Non Definition values
  def doComment(comment: Comment): Unit
  def doAuthorRef(reference: AuthorRef): Unit
  def doBriefDescription(brief: BriefDescription): Unit
  def doDescription(description: Description): Unit
  def doStatement(statement: Statements): Unit
  def doInteraction(interaction: Interaction): Unit
  def doOptionValue(optionValue: OptionValue): Unit

  /** A [[Function]]'s or [[Saga]]'s `requires`/`returns` clause. These are content rather than
    * fields on their container, so a visitor sees them in the position the author wrote them —
    * which is the whole point of the move, since a comment may now sit above or between them.
    */
  def doRequires(requires: Requires): Unit
  def doReturns(returns: Returns): Unit

  /** A [[Group]]'s or [[Epic]]'s `shown by { <url>… }` clause.
    *
    * Same shape as `requires`/`returns` above: it is CONTENT, so a visitor must see it in the
    * position the author wrote it. It had no hook until 2026-08-14 and was skipped outright by
    * `processValue`, on the reasoning that its holder reads it -- true of every visitor except the
    * one that has to write source back out, so prettify deleted every `shown by` it was given.
    */
  def doShownBy(shownBy: ShownBy): Unit

/** An abstract Pass that uses the Visitor pattern
  * (https://refactoring.guru/design-patterns/visitor)
  * @param input
  *   The PassInput to process
  * @param outputs
  *   The outputs of previous passes in case this pass needs it
  */
abstract class VisitingPass[VT <: PassVisitor](
  val input: PassInput,
  val outputs: PassesOutput,
  val visitor: VT
)(using PlatformContext)
    extends HierarchyPass(input, outputs):
  protected final def openContainer(container: Definition, parents: Parents): Unit =
    container match
      case typ: Type              => visitor.openType(typ, parents)
      case module: Module         => visitor.openModule(module, parents)
      case domain: Domain         => visitor.openDomain(domain, parents)
      case context: Context       => visitor.openContext(context, parents)
      case entity: Entity         => visitor.openEntity(entity, parents)
      case adaptor: Adaptor       => visitor.openAdaptor(adaptor, parents)
      case epic: Epic             => visitor.openEpic(epic, parents)
      case uc: UseCase            => visitor.openUseCase(uc, parents)
      case function: Function     => visitor.openFunction(function, parents)
      case saga: Saga             => visitor.openSaga(saga, parents)
      case streamlet: Streamlet   => visitor.openStreamlet(streamlet, parents)
      case repository: Repository => visitor.openRepository(repository, parents)
      case projector: Projector   => visitor.openProjector(projector, parents)
      case handler: Handler       => visitor.openHandler(handler, parents)
      case onClause: OnClause     => visitor.openOnClause(onClause, parents)
      case state: State           => visitor.openState(state, parents)
      case corr: Correlation      => visitor.openCorrelation(corr, parents)
      case group: Group           => visitor.openGroup(group, parents)
      case output: Output         => visitor.openOutput(output, parents)
      case input: Input           => visitor.openInput(input, parents)
      case _: Root                => () // ignore
      case _: Enumerator          => () // not a container
      case _: Field | _: Method | _: Term | _: Author | _: Constant | _: Invariant | _: SagaStep |
          _: Inlet | _: Outlet | _: Connector | _: User | _: Schema | _: Version | _: Copyright |
          _: GenericInteraction | _: SelfInteraction | _: VagueInteraction | _: ContainedGroup |
          _: Definition => // not containers
        () // not  containers
    end match
  end openContainer

  protected final def closeContainer(container: Definition, parents: Parents): Unit =
    container match
      case typ: Type              => visitor.closeType(typ, parents)
      case module: Module         => visitor.closeModule(module, parents)
      case domain: Domain         => visitor.closeDomain(domain, parents)
      case context: Context       => visitor.closeContext(context, parents)
      case entity: Entity         => visitor.closeEntity(entity, parents)
      case adaptor: Adaptor       => visitor.closeAdaptor(adaptor, parents)
      case epic: Epic             => visitor.closeEpic(epic, parents)
      case useCase: UseCase       => visitor.closeUseCase(useCase, parents)
      case function: Function     => visitor.closeFunction(function, parents)
      case saga: Saga             => visitor.closeSaga(saga, parents)
      case streamlet: Streamlet   => visitor.closeStreamlet(streamlet, parents)
      case repository: Repository => visitor.closeRepository(repository, parents)
      case projector: Projector   => visitor.closeProjector(projector, parents)
      case handler: Handler       => visitor.closeHandler(handler, parents)
      case onClause: OnClause     => visitor.closeOnClause(onClause, parents)
      case state: State           => visitor.closeState(state, parents)
      case corr: Correlation      => visitor.closeCorrelation(corr, parents)
      case group: Group           => visitor.closeGroup(group, parents)
      case output: Output         => visitor.closeOutput(output, parents)
      case input: Input           => visitor.closeInput(input, parents)
      case _: Root                => () // ignore
      case _: Field | _: Method | _: Term | _: Author | _: Constant | _: Invariant | _: SagaStep |
          _: Inlet | _: Outlet | _: Connector | _: User | _: Schema | _: Enumerator | _: Version |
          _: Copyright | _: GenericInteraction | _: SelfInteraction | _: VagueInteraction |
          _: ContainedGroup | _: Definition =>
        () // not  containers
    end match
  end closeContainer

  protected final def processLeaf(definition: Leaf, parents: Parents): Unit =
    definition match
      case field: Field                   => visitor.doField(field)
      case method: Method                 => visitor.doMethod(method)
      case author: Author                 => visitor.doAuthor(author)
      case constant: Constant             => visitor.doConstant(constant)
      case invariant: Invariant           => visitor.doInvariant(invariant)
      case version: Version               => visitor.doVersion(version)
      case copyright: Copyright           => visitor.doCopyright(copyright)
      case sagaStep: SagaStep             => visitor.doSagaStep(sagaStep)
      case inlet: Inlet                   => visitor.doInlet(inlet)
      case outlet: Outlet                 => visitor.doOutlet(outlet)
      case connector: Connector           => visitor.doConnector(connector)
      case user: User                     => visitor.doUser(user)
      case schema: Schema                 => visitor.doSchema(schema)
      case relationship: Relationship     => visitor.doRelationship(relationship)
      case containedGroup: ContainedGroup => visitor.doContainedGroup(containedGroup)
    end match
  end processLeaf

  protected final def processValue(value: RiddlValue, parents: Parents): Unit =
    value match
      case comment: Comment =>
        visitor.doComment(comment)
      case authorRef: AuthorRef =>
        visitor.doAuthorRef(authorRef)
      case brief: BriefDescription =>
        visitor.doBriefDescription(brief)
      case description: Description =>
        visitor.doDescription(description)
      case statement: Statement =>
        visitor.doStatement(statement)
      case interaction: Interaction =>
        visitor.doInteraction(interaction)
      case optionValue: OptionValue =>
        visitor.doOptionValue(optionValue)
      case enumerator: Enumerator =>
        visitor.doEnumerator(enumerator)
      case requires: Requires =>
        visitor.doRequires(requires)
      case returns: Returns =>
        visitor.doReturns(returns)
      case shownBy: ShownBy =>
        visitor.doShownBy(shownBy)
      // A Reference reaches here when it is a container's own field rather than a child of a
      // definition -- a Repository's RepositoryRef is the case that occurs. There is nothing for
      // a visitor to do with it: references are visited as part of the definition that holds
      // them, and resolution reads them from the refMap. Enumerated rather than absorbed by a
      // catch-all, so a value kind nobody anticipated fails loudly instead of being skipped.
      //
      // ShownBy sat in this arm until 2026-08-14, on the claim that its holder reads it. Every
      // visitor but one did; prettify has to WRITE it, and so dropped it from its output on every
      // group and epic that had one. The lesson is that "the holder reads it" is a statement about
      // the visitors that exist today, not a property of the node -- so it is a poor reason to
      // withhold a hook.
      case _: Reference[?] => ()
      case _ =>
        throw new IllegalStateException(
          s"processValue has no arm for ${value.getClass.getSimpleName} at ${value.loc}; add one " +
            "-- silently skipping it would drop the node from every visiting pass"
        )
    end match
  end processValue

  override protected final def openInclude(include: Include[?], parents: Parents): Unit =
    visitor.openInclude(include, parents)
  end openInclude

  override protected final def closeInclude(include: Include[?], parents: Parents): Unit =
    visitor.closeInclude(include, parents)
  end closeInclude

  override protected final def openBASTImport(bi: BASTImport, parents: Parents): Unit =
    visitor.openBASTImport(bi, parents)
  end openBASTImport

  override protected final def closeBASTImport(bi: BASTImport, parents: Parents): Unit =
    visitor.closeBASTImport(bi, parents)
  end closeBASTImport
end VisitingPass

/** An abstract PassOutput for use with passes that derive from CollectingPass. This just provides a
  * standard field name for the data that is collected, being `collected`.
  *
  * @param messages
  *   The required messages field from the PassOutput trait
  * @param collected
  *   The data that was collected from the CollectingPass's run
  * @tparam T
  *   The element type of the collected data
  */
abstract class CollectingPassOutput[T](
  root: Root = Root.empty,
  messages: Messages.Messages = Messages.empty,
  collected: Seq[T] = Seq.empty[T]
) extends PassOutput

/** A Pass subclass that processes the AST exactly the same as the depth first search that the Pass
  * class uses. The only difference is that
  *
  * @param input
  *   The PassInput to process
  * @param outputs
  *   The outputs from previous pass runs in case they are needed as input to this CollectingPass
  * @tparam ET
  *   The element type of the collected values
  */
abstract class CollectingPass[ET](input: PassInput, outputs: PassesOutput)(using PlatformContext)
    extends Pass(input, outputs) {

  /** The method usually called for each definition that is to be processed but our implementation
    * of traverse instead calls collect so a value can be returned. This implementation is final
    * because it is meant to be ignored.
    *
    * @param definition
    *   The definition to be processed
    * @param parents
    *   The stack of definitions that are the parents of
    *   [[com.ossuminc.riddl.language.AST.Definition]]. This stack goes from immediate parent
    *   towards the root. The root is deepest in the stack.
    */
  override final def process(definition: RiddlValue, parents: ParentStack): Unit = {
    val collected: Seq[ET] = collect(definition, parents)
    collectedValues ++= collected
  }

  protected val collectedValues: mutable.ArrayBuffer[ET] = mutable.ArrayBuffer.empty[ET]

  /** The processing method called at each node, similar to [[Pass.process]] but modified to return
    * a sequence of the collectable, [[ET]].
    *
    * @param definition
    *   The definition from which an [[ET]] value is collected.
    * @param parents
    *   The parents of the definition
    *
    * @return
    *   One of the collected values, an [[ET]]
    */
  protected def collect(definition: RiddlValue, parents: ParentStack): Seq[ET]

  override def result(root: PassRoot): CollectingPassOutput[ET]
}

/** A companion for Passes to provide entry points and other utilities of general interest */
object Pass {

  /** A PassCreators of the standard passes that should be run on every AST pass. These generate the
    * symbol table, resolve path references, and validate the input. Only after these three have
    * passed successful should the model be considered processable by other passes
    */
  def standardPasses(using PlatformContext): PassCreators =
    val base = Seq(SymbolsPass.creator(), ResolutionPass.creator(), ValidationPass.creator())
    // When completeness warnings are enabled, additionally run the A36 epic/use-case
    // analysis passes so their CompletenessWarnings surface in `riddlc validate`. These
    // are gated behind `showCompletenessWarnings` so that a plain `validate` (completeness
    // off) pays no extra pass cost. Prerequisites first: MessageFlowPass feeds
    // UseCaseWitnessPass; EntityLifecyclePass feeds UseCaseTracePass.
    if summon[PlatformContext].options.showCompletenessWarnings then
      base ++ Seq(
        MessageFlowPass.creator(),
        EntityLifecyclePass.creator(),
        UseCaseWitnessPass.creator(),
        UseCaseTracePass.creator()
      )
    else base
    end if
  end standardPasses

  /** Like standardPasses but uses Quick validation mode, skipping expensive streaming analysis and
    * handler classification. Suitable for interactive/LSP use where speed matters more than
    * exhaustive checks.
    */
  def quickValidationPasses(using PlatformContext): PassCreators =
    Seq(SymbolsPass.creator(), ResolutionPass.creator(), ValidationPass.quickCreator())

  /** A PassesCreate of the passes that extract information but don't do much real work. These
    * generate the symbol table, resolve path references, and calculate statistics. This allows
    * basic information be refreshed without doing a full validation
    */

  def informationPasses(using PlatformContext): PassCreators =
    Seq(SymbolsPass.creator(), ResolutionPass.creator(), StatsPass.creator())

  /** Run a set of passes against some input to obtain a result
    *
    * @param input
    *   The post-parsing input to the passes as a PassInput containing a Root
    * @param passes
    *   The list of Pass construction functions to use to instantiate the passes and run them. The
    *   type
    * @return
    *   A PassesResult which provides the individual
    */
  def runThesePasses(
    input: PassInput,
    passes: PassCreators
  )(using PlatformContext): PassesResult = {
    val outputs = PassesOutput()
    try {
      for pass <- passes yield {
        val aPass = pass(input, outputs)
        val output: PassOutput = runOnePass(input.root, aPass)
        outputs.outputIs(aPass.name, output)
      }
      // Carry any parse-time messages (warnings/deprecations) accumulated during
      // parsing into the result via additionalMessages so they surface to the user.
      PassesResult(input, outputs, input.parseMessages)
    } catch {
      case NonFatal(exception) =>
        // NEVER emit an empty message. `getRootCauseStackTrace` can render to nothing -- observed
        // for a ClassCastException thrown inside ResolutionPass, and earlier for a regex throwing
        // at class-initialisation under Scala Native (see the note at
        // DefinitionValidation.scala:451). Both surfaced as a bare `[severe] empty(1:1->1):` with
        // no text, no source line and no location, which says only "something threw somewhere".
        // ossum.tech spent about half an hour bisecting a model by hand to find one.
        //
        // This is the LAST-RESORT reporter for every in-pass exception, so whatever it prints is
        // all the author gets. `exception.toString` at minimum names the exception class and its
        // message, which is enough to start.
        val stackTrace = ExceptionUtils.getRootCauseStackTrace(exception).mkString("\n")
        val message =
          if stackTrace.trim.nonEmpty then stackTrace
          else
            val described = Option(exception.toString).map(_.trim).filter(_.nonEmpty)
            described.getOrElse(s"${exception.getClass.getName} (no message, no stack trace)")
        val messages: Messages.Messages = List(Messages.severe(message, At.empty))
        PassesResult(input, outputs, messages ++ input.parseMessages)
    }
  }

  /** Run the standard passes with the input provided */
  def runStandardPasses(
    input: PassInput
  )(using PlatformContext): PassesResult = {
    runThesePasses(input, standardPasses)
  }

  /** Run the standard passes on a Root */
  def runStandardPasses(
    model: Root
  )(using PlatformContext): PassesResult = {
    val input: PassInput = PassInput(model)
    runStandardPasses(input)
  }

  /** Run the information passes with the input provided */
  def runInformationPasses(input: PassInput)(using PlatformContext): PassesResult = {
    runThesePasses(input, informationPasses)
  }

  /** Run the information passes on a Root */
  def runInformationPasses(
    model: Root
  )(using PlatformContext): PassesResult = {
    val input: PassInput = PassInput(model)
    runInformationPasses(input)
  }

  /** Run the Symbols Pass */
  def runSymbols(input: PassInput, outputs: PassesOutput)(using PlatformContext): SymbolsOutput = {
    runPass[SymbolsOutput](input, outputs, SymbolsPass(input, outputs))
  }

  /** Run the Resolution Pass */
  def runResolution(input: PassInput, outputs: PassesOutput)(using
    PlatformContext
  ): ResolutionOutput = {
    runPass[ResolutionOutput](input, outputs, ResolutionPass(input, outputs))
  }

  /** Run the Validation pass */
  def runValidation(input: PassInput, outputs: PassesOutput)(using
    PlatformContext
  ): ValidationOutput = {
    runPass[ValidationOutput](input, outputs, ValidationPass(input, outputs))
  }

  /** Run an arbitrary pass */
  def runPass[OUT <: PassOutput](input: PassInput, outputs: PassesOutput, pass: Pass)(using
    PlatformContext
  ): OUT = {
    val output: OUT = Pass.runOnePass(input.root, pass).asInstanceOf[OUT]
    outputs.outputIs(pass.name, output)
    output
  }

  private def runOnePass(
    root: PassRoot,
    mkPass: => Pass
  )(using io: PlatformContext): PassOutput = {
    val pass: Pass = mkPass
    Timer.time[PassOutput](pass.name, io.options.showTimes) {
      val parents: ParentStack = ParentStack.empty
      val root1: PassRoot = pass.preProcess(root)
      pass.traverse(root1, parents)
      pass.postProcess(root1)
      pass.close()
      pass.result(root1)
    }
  }
}
